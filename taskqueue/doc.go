// Package taskqueue defines transport-neutral task queue contracts: Task
// envelopes, processors and routing, enqueue policy, periodic enqueue
// definitions, middleware, and worker lifecycle interfaces. Provider adapters,
// such as github.com/go-jimu/contrib/taskqueue/asynq, map them onto a concrete
// system and own storage, acknowledgement, retry, dead-letter, and locking
// behavior.
//
// Application code imports only this package: it builds Task values, enqueues
// them through an Enqueuer, and implements Processor. The provider adapter and
// its SDK are imported in runtime composition only, which constructs the
// adapter, registers processors on it, and starts and stops it.
//
// # Vocabulary
//
// TaskType is the semantic contract that routes a task to its processor and
// names its payload schema; providers map it to their own topics, streams, or
// keys. Queue is an optional provider-facing lane name. The payload schema is
// TaskType plus the registered Go payload type; PayloadCodec (JSON, protobuf,
// YAML, TOML) is only the byte encoding. ID is a caller-assigned identity for
// one unit of work. ExecutionInfo carries provider worker metadata for the
// current attempt through context; payloads carry only business data.
//
// # Processing
//
// A Router holds exactly one Processor per TaskType and returns
// ErrDuplicateProcessor for a second one. Write a processor in one of two
// forms:
//
//   - A struct that implements Processor (TaskType plus Process), when the
//     processor has dependencies such as repositories or an application
//     service, injected through its constructor. This is the usual form in
//     application code.
//   - NewProcessor(taskType, fn), when the work fits in a closure: tests,
//     small runtime tasks, or wrapping fn with Chain and Middleware.
//
// Process decodes the payload with DecodeJSON, DecodeProto, DecodePayload, or
// a SchemaRegistry, does the work, and reports the outcome:
//
//   - nil: the task is done.
//   - an error: the attempt failed and the provider retries it within the
//     task's retry budget (WithMaxRetry or the provider default), then keeps
//     or discards it as the provider documents.
//   - an error wrapping ErrSkipRetry, for example
//     fmt.Errorf("%w: account closed", taskqueue.ErrSkipRetry): the failure is
//     permanent and the provider stops retrying at once. When the codec
//     rejects the payload bytes, DecodeJSON, DecodeProto, DecodePayload,
//     DecodePayloadWithCodec, and the SchemaRegistry Decode methods already
//     wrap ErrSkipRetry, because those bytes fail on every attempt. Their
//     other errors, such as ErrUnknownType or ErrUnknownPayloadCodec, do not.
//
// To wrap a struct Processor in middleware, register
// NewProcessor(p.TaskType(), Chain(p.Process, Recover(), Logging(logger))).
// The first middleware passed to Chain is the outermost.
//
// Router.Process returns ErrUnhandledType for a task type with no processor.
// The Recover middleware turns a panic into an error wrapping ErrPanic. A
// provider may deliver a task more than once, such as after a timeout or a
// worker crash, so make processors idempotent.
//
// # Creating and enqueueing tasks
//
// Create the envelope at the application boundary. New takes raw bytes,
// NewJSONTask and NewProtoTask encode one format, NewEncodedTask takes any
// registered codec, and SchemaRegistry derives the Definition from the
// payload's Go type. For protobuf, the payload is the type generated by
// protoc-gen-go. Task metadata, including WithID and WithHeader, are Option
// values passed when creating the task. Policy is EnqueueOption values passed
// to Enqueuer.Enqueue; an option left unset means the provider default, while
// a set option applies as given, so WithMaxRetry(0) means no retries.
//
// The caller validates enqueue policy with NewEnqueueOptions(opts...).Validate()
// before Enqueue; Enqueuer states this contract.
//
// # Task ID
//
// WithID names one unit of work, such as one user's welcome email
// ("welcome-email:user-1"), rather than a stream of work such as all of a
// user's tasks. A provider keeps at most one task per ID while it retains that
// task, which can include pending tasks, retries, archived failures, and
// completed tasks kept for inspection. Enqueue returns an error matching
// ErrDuplicateTask for an ID that is still retained; treat it as "this work is
// already scheduled or was kept after it ran". Each adapter documents how long it retains an ID. WithID
// deduplicates by identity; WithUnique(ttl) deduplicates by content for a time
// window. Neither orders tasks.
//
// # Periodic tasks
//
// A PeriodicTask enqueues the same static envelope with the same policy on
// every schedule fire, so every value in it must stay valid across fires:
//
//   - Timing is relative: use WithDelay and WithTimeout. NewPeriodicTask
//     rejects WithProcessAt and WithDeadline with ErrInvalidPeriodicTaskPolicy.
//   - The task has no ID: a fixed ID would conflict with any earlier fire the
//     provider still retains, and NewPeriodicTask returns ErrPeriodicTaskID.
//     Use WithUnique to suppress overlapping fires.
//
// PeriodicTask.Name is the registration key within one registrar;
// registering a name twice returns ErrDuplicatePeriodicTask. Scheduler
// leadership across replicas, payloads computed per fire, and workflow
// orchestration belong to the provider or application. CronSchedule checks
// the portable five-field shape and an optional IANA location;
// IntervalSchedule is duration-based and takes no location.
//
// # Lifecycle
//
// Registrar.Register only registers a processor; it starts nothing. A
// provider runtime implements Worker (Start and Shutdown, for lifecycle hooks)
// or Runner (a blocking Run that returns nil when ctx ends). Run reports only
// startup and shutdown failures; each adapter documents where failures after
// startup surface.
//
// # Provider adapters
//
// An adapter's documentation states how it encodes TaskType, Queue, ID,
// Headers, PayloadCodec, and payload bytes; how long it retains a task ID,
// returning ErrDuplicateTask for conflicts; how each enqueue option maps to
// the provider and which fields define a WithUnique duplicate; how processor
// errors are retried, archived, or dropped, and what ErrSkipRetry does;
// whether registration works after start; and how failures after startup
// surface. README.md expands this into a checklist.
